def cut_strokes(y, sr: int, step_sec: float, target_lufs: float):
    """打鍵の録音から**押し込みだけ**を切り出し、連なりで音量を揃える。

    ⚠⚠ **1 発ずつ正規化しない。切り出した全部に同じ倍率を掛ける。**
    1 発ずつ揃えると、材料が持っている打鍵の強弱（強い打・弱い打）が消えて、
    等間隔・等音量で鳴る機械の音になる。素材の生きている所を殺さない。

    ⚠ 音量は **`step_sec` 間隔で連ねた状態**で測る。1 発の LUFS で揃えると、
    実際に耳へ届く「打っているあいだの高さ」から外れる（連なると密度のぶん上がる）。
    """
    st = sk.to_stereo(y)
    env = np.max(np.abs(st), axis=1)
    on_thr, guard = 10 ** (CUT_ONSET_DB / 20), int(CUT_GUARD * sr)

    heads, i = [], 0
    while i < len(env):
        if env[i] > on_thr:
            heads.append(i)
            i += guard
        else:
            i += 1

    cuts, rel_min = [], 1e9
    for s in heads:
        a = max(0, s - int(CUT_PRE * sr))
        cuts.append(sk.env_fade(st[a:a + int((CUT_PRE + CUT_BODY) * sr)], 0.0, CUT_FADE))
        # 戻りの山（押し込みの 40〜200ms 後でいちばん大きい所）。**床の小さな瘤に釣られない**
        # ように、閾値ではなく最大値で見る。
        lo, hi = s + int(0.04 * sr), min(len(env), s + int(0.20 * sr))
        if hi > lo:
            rel_min = min(rel_min, (lo + int(np.argmax(env[lo:hi])) - s) / sr)

    if not cuts:
        return [], 0.0, -70.0, 0.0
    stream = stroke_stream(cuts, sr, step_sec)
    gain = 10 ** ((target_lufs - sk.lufs(stream)) / 20.0)
    # 天井（-3dBTP）は連なりでも 1 発でも越えさせない。
    tp = max(sk.true_peak_db(c * gain) for c in cuts)
    if tp > -3.0:
        gain *= 10 ** ((-3.0 - tp) / 20.0)
    cuts = [c * gain for c in cuts]
    return cuts, gain, sk.lufs(stroke_stream(cuts, sr, step_sec)), rel_min


def stroke_stream(cuts, sr: int, step_sec: float, repeat: int = 3):
    """切り出しを刻み秒で並べた連なり（**測るためのもの**。焼かない）。

    順番を回すのは、同じ波形が並んだときだけ起きる干渉で音量を誤らないため。
    ⚠ 尺は 400ms の窓が何個か入る長さが要る（LUFS はゲート付きの平均なので）。
    """
    step = int(step_sec * sr)
    n = len(cuts) * repeat
    tail = max(len(c) for c in cuts)
    out = np.zeros((step * n + tail, 2))
    for k in range(n):
        c = cuts[k % len(cuts)]
        out[k * step:k * step + len(c)] += c
    return out


def norm_lufs_drive(y, target: float, max_drive_db: float = 12.0):
    """ラウドネスを target へ合わせる。**届かなければ尖頭を丸めて届かせる。**

    `make-sounds.py` の `norm_lufs` と同じ探索（丸めは必要なぶんだけ・上限つき）。
    届かなければ「届かなかった」まま返す（黙って歪ませるより数字で足りないと言う方がよい）。
    """
    drive = 0.0
    best = y * (10 ** ((target - sk.lufs(y)) / 20.0))
    while True:
        z = sk.soft_clip(y, drive) if drive > 0 else y
        z = z * (10 ** ((target - sk.lufs(z)) / 20.0))
        tp = sk.true_peak_db(z)
        if tp <= -3.0:
            return z
        best = z * (10 ** ((-3.0 - tp) / 20.0))
        if drive >= max_drive_db:
            return best
        drive = min(max_drive_db, drive + 2.0)


SILENCE_DB = -60.0     # これより静かな端は落とす
EDGE_FADE = 0.008      # 端のクリック止め（秒）


def decode(src: str, dst: str) -> bool:
    import imageio_ffmpeg
    exe = imageio_ffmpeg.get_ffmpeg_exe()
    r = subprocess.run([exe, "-y", "-v", "error", "-i", src,
                        "-ar", str(sk.SR), "-ac", "2", "-c:a", "pcm_s16le", dst],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        print(f"  復号に失敗: {os.path.basename(src)}\n    {r.stderr.strip()[:200]}")
        return False
    return True


def loudest_sec(y: np.ndarray, sr: int, win: float = 0.40) -> float:
    """**いちばん大きいところ**（<paramref name="win"/> 秒窓の実効値が最大になる時刻の中央）。

    ⚠ 尖頭ではなく窓の実効値で測る。1 標本の尖頭は「大きく聞こえる所」とは限らない
    （`rules/sound-design.md` §3 の「ピークで揃えない」と同じ理由）。
    """
    m = sk.to_stereo(np.asarray(y)).mean(axis=1)
    n = int(win * sr)
    if len(m) <= n:
        return len(m) / sr / 2.0
    c = np.cumsum(np.concatenate([[0.0], m ** 2]))
    e = (c[n:] - c[:-n])
    return (int(np.argmax(e)) + n / 2.0) / sr


def trim(y: np.ndarray) -> np.ndarray:
    """前後の無音を落とす。**中の無音は触らない**（間も作品のうち）。"""
    m = np.max(np.abs(sk.to_stereo(y)), axis=1)
    thr = 10 ** (SILENCE_DB / 20)
    idx = np.flatnonzero(m > thr)
    if len(idx) == 0:
        return y
    a = max(0, idx[0] - int(0.005 * sk.SR))
    b = min(len(y), idx[-1] + int(0.05 * sk.SR))
    return y[a:b]


def fold_loop(y: np.ndarray, xf: float = LOOP_XF) -> np.ndarray:
    """尻 <paramref name="xf"/> 秒を頭へ等パワーで折り返し、継ぎ目の無いループにする。

    出来上がりは `xf` 秒だけ短い。巻き戻る瞬間に鳴っているのは「尻と頭が混ざった区間」なので、
    密度も音量も途切れない（`sound-lint.py` の `jump` が数値で確かめる）。
    """
    st = sk.to_stereo(y)
    n = int(xf * sk.SR)
    if n <= 0 or len(st) < n * 3:
        return st
    head, tail, body = st[:n], st[-n:], st[:-n]
    t = np.linspace(0.0, 1.0, n, endpoint=False)[:, None]
    # 等パワー（線形だと混ざっている最中に音の密度が凹む）。
    body = body.copy()
    body[:n] = head * np.sqrt(t) + tail * np.sqrt(1.0 - t)
    return body


def ingest_cuts(cuts, src_dir: str) -> None:
    """1 本の録音を 1 発ずつに切って焼く（<see cref="CUTS"/>）。"""
    for jp, name, expect, target, step, _why in cuts:
        src = os.path.join(src_dir, jp)
        raw = os.path.join(RAW, f"src_{name}.wav")
        if os.path.exists(src):
            if not decode(src, raw):
                continue
        elif not os.path.exists(raw):
            print(f"  無い: {jp}（{src_dir} にも {RAW} にも）")
            continue
        else:
            print(f"  元 mp3 が無いので復号済みを使う: {name}")

        y, sr = sk.read_wav(raw)
        segs, gain, stream_lufs, rel_min = cut_strokes(y, sr, step, target)
        if segs and rel_min < CUT_BODY + CUT_RELEASE_MARGIN:
            # ⚠ 切り出しに**戻り**が入っている ＝ 密度が倍になる。CUT_BODY を詰めること。
            print(f"  ⚠ {name}: 戻りの山まで最短 {rel_min * 1000:.1f}ms しかない"
                  f"（切り出し {CUT_BODY * 1000:.0f}ms ＋ 余白 {CUT_RELEASE_MARGIN * 1000:.0f}ms）")
        if len(segs) != expect:
            # ⚠ **黙って本数を変えない。** 出力名は `_1..N` なので、本数が変わると
            #    実行時の変種の数（`TypeAudioCue`）と食い違い、無い音を掴もうとする。
            print(f"  ⚠ {name}: {expect} 発のはずが {len(segs)} 発だった。"
                  f"元ファイルか CUT_* の閾値を確かめること")
        for i, seg in enumerate(segs):
            segs[i] = emit(f"{name}_{i + 1}", seg)
        if not segs:
            continue
        print(f"  {name}_1..{len(segs)}  倍率 {20 * np.log10(max(gain, 1e-9)):+.1f}dB  "
              f"連なり {stream_lufs:.1f} LUFS（{1 / step:.0f} 発/秒）  "
              f"戻りの山まで最短 {rel_min * 1000:.1f}ms")
        for i, seg in enumerate(segs):
            d = sk.describe(seg)
            print(f"    {name}_{i + 1}  {d['sec'] * 1000:5.1f}ms  {d['lufs']:6.1f} LUFS  "
                  f"tp {d['true_peak_db']:5.1f}dB  鋭さ {d['sharp']:4.2f}  "
                  f"粗さ {d['rough']:4.2f}  内蔵SP {d['speaker_db']:5.1f}dB")


def mix_build(y, sr: int, base: np.ndarray, body_sec: float, rel_db: float,
              ref_lufs: float = None, at_sec: float = 0.0):
    """もらった音の 1 発を切り出して、既に焼いた土台へ重ねる（<see cref="MIXES"/>）。

    ⚠ **音量は土台との関係で決める。** 「小さめ」は絶対値ではなく「通常の切替音がメイン」という
    関係のことなので、土台のラウドネスを基準に `rel_db` だけ下げる。
    ⚠⚠ **土台が家族（変種）のときは `ref_lufs` に 1 本目の高さを渡す。** 各変種のラウドネスは
    尺の関数なので、そのまま基準にすると**警報の大きさが切り替えのたびに変わる**（0112）。
    ⚠ `at_sec` は土台の頭から警告を置く位置。**頭の一撃（土台の 0〜15ms）に警告の立ち上がりを
    重ねない**ためのもので、融合の窓（約 30ms）の内側なら「音が 2 つ」には聞こえない。
    ⚠ 返す `seg` は**置いた位置に合わせて頭に無音を足したもの**（呼んだ側が土台と引き算で
    突き合わせられるように、長さも合成と同じにしてある）。
    """
    st = sk.to_stereo(trim(y))
    env = np.max(np.abs(st), axis=1)
    thr = 10 ** (MIX_ONSET_DB / 20)
    head = int(np.argmax(env > thr)) if np.any(env > thr) else 0
    a = max(0, head - int(MIX_PRE * sr))
    seg = sk.env_fade(st[a:a + int((MIX_PRE + body_sec) * sr)], MIX_IN, MIX_FADE)
    ref = sk.lufs(base) if ref_lufs is None else ref_lufs
    seg = seg * 10 ** ((ref + rel_db - sk.lufs(seg)) / 20.0)

    i0 = max(0, int(at_sec * sr))
    n = max(len(base), i0 + len(seg))
    out = np.zeros((n, 2))
    out[:len(base)] += base
    placed = np.zeros((n, 2))
    placed[i0:i0 + len(seg)] += seg
    out += placed
    # ⚠ 天井に当たったら**両方まとめて**下げる（土台だけ下げると主従の関係が崩れる）。
    tp = sk.true_peak_db(out)
    if tp > -3.0:
        g = 10 ** ((-3.0 - tp) / 20.0)
        out, placed = out * g, placed * g
    return out, placed


def soft_level(y: np.ndarray, th_db: float, ratio: float,
               att: float = 0.012, rel: float = 0.180) -> np.ndarray:
    """音節どうしの差だけを詰める（`VOICES` の `level`）。

    ⚠ **これは §4.5 の例外**。ユーザーが「聞き心地が悪くない程度に加工」と指示したぶんだけ掛ける。
    比 2.0 は「差を半分にする」という意味で、素材の起伏そのものは残る
    （実測: 「あー」と「そーぼー」の差 11.5dB → 6.2dB）。

    ⚠ 検出は**両チャンネルの最大**で行い、掛ける倍率は左右で同じにする
    （別々に掛けると声が左右に揺れる）。
    """
    x = y * 10 ** (VOICE_PRE_DB / 20.0)      # ⚠ 閾値は下駄を履かせた後の値で書いてある
    key = np.max(np.abs(x), axis=1)
    a = math.exp(-1.0 / (sk.SR * att))
    r = math.exp(-1.0 / (sk.SR * rel))
    th = 10 ** (th_db / 20.0)
    g = np.empty(len(key))
    env = 0.0
    for i, v in enumerate(key):
        env = a * env + (1 - a) * v if v > env else r * env + (1 - r) * v
        if env > th:
            edb = 20 * math.log10(env + 1e-12)
            g[i] = 10 ** ((th_db + (edb - th_db) / ratio - edb) / 20.0)
        else:
            g[i] = 1.0
    return (x * g[:, None]) * 10 ** (-VOICE_PRE_DB / 20.0)


def ingest_voices(voices, src_dir: str) -> None:
    """もらった声を、聞ける所まで手当てして焼く（<see cref="VOICES"/>）。"""
    for v in voices:
        name = v["name"]
        src = os.path.join(src_dir, v["src"])
        raw = os.path.join(RAW, f"src_{name}.wav")
        if os.path.exists(src):
            if not decode(src, raw):
                continue
        elif not os.path.exists(raw):
            print(f"  無い: {v['src']}（{src_dir} にも {RAW} にも）")
            continue
        else:
            print(f"  元の録音が無いので復号済みを使う: {name}")

        y, _sr = sk.read_wav(raw)
        y = sk.to_stereo(y)
        before = sk.describe(y)

        t0, t1 = v["cut"]
        y = y[int(t0 * sk.SR):int(t1 * sk.SR)]
        if v.get("hp"):
            y = sk.biquad(y, "hp", v["hp"])
        if v.get("shelf"):
            fc, db = v["shelf"]
            y = sk.biquad(y, "hs", fc, gain_db=db)
        if v.get("level"):
            y = soft_level(y, *v["level"])
        fi, fo = v.get("fade", (EDGE_FADE, EDGE_FADE))
        y = sk.env_fade(y, fi, fo)

        # ⚠ **ラウドネス合わせは 1 回では決まらない。** R128 は絶対ゲート（-70 LUFS）を持つので、
        #    持ち上げると今まで数えていなかった小さな区間が数に入り、狙いから 0.5dB ほど外れる
        #    （実測: 1 回だと -20.0 のつもりで -20.5 になった）。落ち着くまで回す。
        for _ in range(6):
            d_db = v["lufs"] - sk.lufs(y)
            y = y * 10 ** (d_db / 20.0)
            if abs(d_db) < 0.05:
                break
        tp = sk.true_peak_db(y)
        if tp > -3.0:
            y = y * 10 ** ((-3.0 - tp) / 20.0)

        y = emit(name, y)
        d = sk.describe(y)
        print(f"  {name:16s} {before['sec']:5.2f}s → {d['sec']:5.2f}s   "
              f"{before['lufs']:6.1f} → {d['lufs']:6.1f} LUFS   "
              f"tp {before['true_peak_db']:5.1f} → {d['true_peak_db']:5.1f}dB   "
              f"鋭さ {d['sharp']:4.2f} 粗さ {d['rough']:4.2f} 内蔵SP {d['speaker_db']:5.1f}dB")


def ingest_mixes(mixes, src_dir: str) -> None:
    """既に焼いた音へ、もらった音を薄く重ねて焼く（<see cref="MIXES"/>）。

    ⚠ **土台の本数ぶん焼く。** 警告の高さは**常に 1 本目**を基準にするので、
    どの番号で鳴っても同じ警報の大きさになる。
    """
    for jp, base_stem, stem, count, body, rel, at, _why in mixes:
        src = os.path.join(src_dir, jp)
        raw = os.path.join(RAW, f"src_{stem}.wav")
        if os.path.exists(src):
            if not decode(src, raw):
                continue
        elif not os.path.exists(raw):
            print(f"  無い: {jp}（{src_dir} にも {RAW} にも）")
            continue
        else:
            print(f"  元 mp3 が無いので復号済みを使う: {stem}")

        first = os.path.join(OUT, f"{base_stem}_1.wav")
        if not os.path.exists(first):
            # ⚠ 土台が無いまま焼くと「警告音だけ」が切替音の名前で出来る（無音より悪い）。
            print(f"  土台が無い: {base_stem}_1.wav（先にそちらを焼くこと）")
            continue
        ref_lufs = sk.lufs(sk.to_stereo(sk.read_wav(first)[0]))

        y, sr = sk.read_wav(raw)
        print(f"  {stem}_1..{count}  ＋ 警告 {body * 1000:.0f}ms を頭から {at * 1000:.0f}ms に"
              f"（1 本目に対し {rel:+.1f}dB ＝ {count} 本とも同じ高さ）")
        for i in range(1, count + 1):
            base_path = os.path.join(OUT, f"{base_stem}_{i}.wav")
            if not os.path.exists(base_path):
                print(f"    土台が無い: {base_stem}_{i}.wav")
                continue
            base = sk.to_stereo(sk.read_wav(base_path)[0])
            out, seg = mix_build(y, sr, base, body, rel, ref_lufs, at)
            out = emit(f"{stem}_{i}", out)
            d, b, g = sk.describe(out), sk.describe(base), sk.describe(seg)
            # ⚠ 「土台がメイン」は**頭 20ms の実効値**で見る（統合 LUFS は警告の尺で動くので使えない）。
            head_n = int(0.020 * sr)
            def _db(z):
                return 20 * np.log10(max(float(np.sqrt(np.mean(z[:head_n] ** 2))), 1e-9))
            print(f"    {stem}_{i:<12d} 土台 {b['lufs']:6.1f} → 合成 {d['lufs']:6.1f} LUFS   "
                  f"tp {d['true_peak_db']:5.2f}dB   警告だけ {g['lufs']:6.1f} LUFS   "
                  f"頭20ms 土台 {_db(base):5.1f} / 合成 {_db(out):5.1f}dBFS   "
                  f"鋭さ {d['sharp']:4.2f}   内蔵SP {d['speaker_db']:5.1f}dB")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--src", default=DOWNLOADS)
    # ⚠ 1 本だけ焼き直すための口。全部を焼き直すと、**別のシュビーが直したばかりの音**まで
    #    書き戻すことになる（並列で作業しているのが普通のリポジトリなので既定にしない）。
    ap.add_argument("--only", nargs="*", default=None, metavar="名前",
                    help="この出力名だけを焼く（例: --only bed_room_lap2 bed_room_lap3）")
    a = ap.parse_args()

    if a.list:
        for jp, name, how, target, why in PLAN:
            print(f"  {name:16s} ← {jp}\n      {how} {target:+.1f} / {why}")
        for jp, name, n, target, step, why in CUTS:
            print(f"  {name+'_1..'+str(n):16s} ← {jp}\n      切り出し / 連なり {target:+.1f} LUFS"
                  f"（{1/step:.0f} 発/秒）/ {why}")
        jp, stem = SWITCH_SRC
        print(f"  {stem+'_1..'+str(len(SWITCH_VARIANTS)):16s} ← {jp}")
        print(f"      尾の来る時刻・長さ・高さ・音程を変えた変種 / 1 本目を {SWITCH_LUFS:+.1f} LUFS へ")
        for i, v in enumerate(SWITCH_VARIANTS, start=1):
            print(f"        {i}: 粒{v[5]} 頭x{v[0]:.3f} 尾@{v[1]*1000:.0f}ms "
                  f"{v[2]*1000:.0f}ms x{v[3]:.3f} {v[4]:+.1f}dB — {v[6]}")
        jp, stem = EYE_SRC
        print(f"  {stem+'_1..'+str(len(EYE_VARIANTS)):16s} ← {jp}")
        print(f"      尾の来る時刻・長さ・高さ・音程を変えた変種 / 1 本目を {EYE_LUFS:+.1f} LUFS へ")
        for jp, name, target, why in SWARMS:
            print(f"  {name:16s} ← {jp}\n      小刻みに並べる / 頭 0.5s を {target:+.1f} LUFS へ"
                  f"（{SWARM_SEC:.2f}s）/ {why}")
        for jp, name, target, why in CHORUS:
            print(f"  {name:16s} ← {jp}\n      重ねて輪にする / {target:+.1f} LUFS"
                  f"（{CHORUS_SEC:.1f}s・{len(CHORUS_VOICES)} 回）/ {why}")
        for jp, _stem, why in SWELL:
            layers = " + ".join(f"{n}({s:.0f}s・{len(v)} 回)" for n, s, v in SWELL_LAYERS)
            print(f"  {'（増える 3 枚）':16s} ← {jp}\n      {layers}"
                  f"\n      1 体ぶん {SWELL_SOLO_LUFS:+.1f} LUFS で 3 枚まとめて揃える / {why}")
        for jp, base_stem, stem, count, body, rel, at, why in MIXES:
            print(f"  {stem+'_1..'+str(count):16s} ← {base_stem}_1..{count} ＋ {jp}")
            print(f"      1 発から {body * 1000:.0f}ms を {rel:+.1f}dB（1 本目基準）で"
                  f"頭から {at * 1000:.0f}ms に重ねる / {why}")
        for v in VOICES:
            t0, t1 = v["cut"]
            print(f"  {v['name']:16s} ← {v['src']}")
            print(f"      {t0:.3f}〜{t1:.3f}s を切り出し / 低域切り {v['hp']:.0f}Hz / "
                  f"高域 {v['shelf'][1]:+.1f}dB / 圧縮 {v['level'][1]:.1f}:1 / "
                  f"{v['lufs']:+.1f} LUFS / {v['why']}")
        return 0

    eye_names = {f"{EYE_SRC[1]}_{i}" for i in range(1, len(EYE_VARIANTS) + 1)}
    switch_names = {f"{SWITCH_SRC[1]}_{i}" for i in range(1, len(SWITCH_VARIANTS) + 1)}
    alert_names = {f"{m[2]}_{i}" for m in MIXES for i in range(1, m[3] + 1)}
    names = ({p[1] for p in PLAN} | {c[1] for c in CUTS}
             | {s[1] for s in SWARMS} | {c[1] for c in CHORUS}
             | {n for n, _s, _v in SWELL_LAYERS} | alert_names
             | switch_names | {SWITCH_SRC[1]}
             | eye_names | {EYE_SRC[1]}
             | {v["name"] for v in VOICES})
    if a.only is not None and not set(a.only) <= names:
        missing = sorted(set(a.only) - names)
        print(f"  PLAN にも CUTS にも無い名前: {', '.join(missing)}")
        return 1
    plan = [p for p in PLAN if a.only is None or p[1] in a.only]
    cuts = [c for c in CUTS if a.only is None or c[1] in a.only]
    swarms = [s for s in SWARMS if a.only is None or s[1] in a.only]
    chorus = [c for c in CHORUS if a.only is None or c[1] in a.only]
    # ⚠ 増える 3 枚は**家族で 1 つ**（1 枚目の高さで 3 枚を揃えるので、1 枚だけ焼き直せない）。
    swell = SWELL if (a.only is None
                      or any(n in a.only for n, _s, _v in SWELL_LAYERS)) else []
    # ⚠ 目の一撃も**家族で 1 つ**（切替と同じ理由）。
    eyes = (EYE_VARIANTS if (a.only is None or EYE_SRC[1] in a.only
                             or bool(eye_names & set(a.only))) else [])
    # ⚠ 切替の変種は**家族で 1 つ**（1 本目で決めた丸めと倍率を 6 本へ掛けるので 1 本だけ焼けない）。
    switch = (SWITCH_VARIANTS if (a.only is None or SWITCH_SRC[1] in a.only
                                  or bool(switch_names & set(a.only))) else [])
    # ⚠ 重ねる音は**土台と対**。`--only <土台>` でも焼き直す（土台だけ新しいと食い違う）。
    mixes = [m for m in MIXES
             if a.only is None or bool(alert_names & set(a.only)) or m[1] in a.only
             or bool(switch_names & set(a.only))]
    voices = [v for v in VOICES if a.only is None or v["name"] in a.only]

    os.makedirs(RAW, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    ingest_voices(voices, a.src)
    ingest_switch(switch, a.src)
    ingest_eyes(eyes, a.src)
    ingest_cuts(cuts, a.src)
    ingest_swarms(swarms, a.src)
    ingest_chorus(chorus, a.src)
    ingest_swell(swell, a.src)
    for jp, name, how, target, _why in plan:
        src = os.path.join(a.src, jp)
        raw = os.path.join(RAW, f"src_{name}.wav")
        if os.path.exists(src):
            if not decode(src, raw):
                continue
        elif not os.path.exists(raw):
            print(f"  無い: {jp}（{a.src} にも {RAW} にも）")
            continue
        else:
            print(f"  元 mp3 が無いので復号済みを使う: {name}")

        y, sr = sk.read_wav(raw)
        # ⚠ **切り出しがいちばん先**（`SLICE`）。折り返しも音量合わせも切ったあとの中身で決める。
        # ⚠⚠ **測る前に切る。** `describe` は帯域・鋭さ・粗さを全長で解くので、15 分の素材
        #    （ホワイトノイズ）を切る前に測ると**数分かかる**（2026-09-03 に実際に待った）。
        if name in SLICE:
            # ⚠ 変数名に `a` / `b` を使わない（`a` は argparse の名前空間・この関数の引数）。
            #    2026-09-03 に影を作って `sfx_eye_big` だけ焼けなかった。
            cut_from, cut_to = SLICE[name]
            y = y[int(cut_from * sr):int(cut_to * sr)]
        before = sk.describe(y)
        # ⚠ ループにする音は **端を落とさない**（頭と尻の無音がそのまま折り返しの材料になる）。
        #    切ってから折り返すと、素材の「入り」と「終わり」の空気が消えて別の音になる。
        if name.startswith("bed_"):
            y = fold_loop(y)
        else:
            y = sk.to_stereo(trim(y))
            y = sk.env_fade(y, EDGE_FADE, EDGE_FADE)
        # ⚠⚠ **いちばん大きいところを、鳴らしてから何秒目に置くか**（`ALIGN`・0131）。
        #    頭へ無音を足すだけで、音そのものは 1 ビットも触らない。
        if name in ALIGN:
            want = ALIGN[name]
            at = loudest_sec(y, sr)
            pad = int(round((want - at) * sr))
            if pad > 0:
                y = np.concatenate([np.zeros((pad, y.shape[1])), y], axis=0)
            elif pad < 0:
                y = y[-pad:]
            print(f"    {name}: いちばん大きいところ {at:.3f}s → {loudest_sec(y, sr):.3f}s"
                  f"（狙い {want:.3f}s・頭へ {pad / sr:+.3f}s）")

        # ⚠ **音量を揃える前に掛ける**（削った分だけラウドネスが下がるので、後に掛けると狙いが外れる）。
        if name in TAME:
            fc, db, oct_w = TAME[name]
            y = np.stack([sk.spec_shape(y[:, ch], lambda f: sk.shelf(f, fc, db, oct_w))
                          for ch in (0, 1)], axis=1)

        if how == "peak":
            tp = sk.true_peak_db(y)
            y = y * 10 ** ((target - tp) / 20.0)
        elif how == "lufs!":
            # ⚠⚠ **尖頭を丸めてでも狙いの高さまで持ち上げる**（2026-08-13・`canon/LEDGER.md` 0032）。
            #    素の音量合わせだけでは、**波高の大きい一撃は -3dBTP の天井に当たって上がらない**
            #    （`sfx_screen_on` は本体が 0.2 秒・波高 17.6dB で、-17.0 LUFS のまま
            #     「鳴っていないように聞こえる」とユーザー判定）。
            #    ⚠ これは §4.5「もらった音を良くしようとしない」の例外ではなく**音量合わせの側**。
            #       イコライザも圧縮も掛けず、必要なぶんだけ尖頭を丸めて高さを出す
            #       （合成の音が `make-sounds.norm_lufs` で受けているのと同じ扱い）。
            y = norm_lufs_drive(y, target)
        else:
            y = y * 10 ** ((target - sk.lufs(y)) / 20.0)
            tp = sk.true_peak_db(y)
            if tp > -3.0:
                y = y * 10 ** ((-3.0 - tp) / 20.0)

        y = emit(name, y)
        d = sk.describe(y)
        print(f"  {name:16s} {before['sec']:5.2f}s → {d['sec']:5.2f}s   "
              f"{before['lufs']:6.1f} → {d['lufs']:6.1f} LUFS   "
              f"tp {before['true_peak_db']:5.1f} → {d['true_peak_db']:5.1f}dB   "
              f"鋭さ {d['sharp']:4.2f} 粗さ {d['rough']:4.2f} 内蔵SP {d['speaker_db']:5.1f}dB")
    # ⚠ **土台を焼いた後に呼ぶ**（PLAN のループの後）。順番を変えると 1 世代古い土台へ重ねる。
    ingest_mixes(mixes, a.src)
    print(f"\n→ {OUT}\n次: py -3.11 tools/sound-lint.py  →  .\\tools\\unity.ps1 menu sound-import")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
