def ingest_chorus(chorus, src_dir: str) -> None:
    """1 本の声を重ねて焼く（<see cref="CHORUS"/>）。"""
    for jp, name, target, _why in chorus:
        src = os.path.join(src_dir, jp)
        raw = os.path.join(RAW, f"src_{name}.wav")
        if os.path.exists(src):
            if not decode(src, raw):
                continue
        elif not os.path.exists(raw):
            print(f"  無い: {jp}（{src_dir} にも {RAW} にも）")
            continue
        else:
            print(f"  元 mp3 が無いので復号済みを使う: {name}")

        y, sr = sk.read_wav(raw)
        tracks, counts, spans, total = chorus_build(y, sr, target)
        n = len(tracks)
        # ⚠ **足した状態の高さが設計値**（-30.5 LUFS）。1 体ずつの数字ではない。
        print(f"  {name:16s} {n} 体 / {len(spans)} 回 / {total:.1f}s   "
              f"足すと {sk.lufs(sum_tracks(tracks)):6.1f} LUFS（狙い {target:+.1f}）")
        for i, t in enumerate(tracks):
            t = emit(body_name(name, i, n), t)
            d = sk.describe(t)
            print(f"    {body_name(name, i, n):20s} {counts[i]} 回  {d['lufs']:6.1f} LUFS  "
                  f"tp {d['true_peak_db']:5.1f}dB  鋭さ {d['sharp']:4.2f} "
                  f"粗さ {d['rough']:4.2f}  内蔵SP {d['speaker_db']:5.1f}dB")
        out = sum_tracks(tracks)
        # 重なりの様子（0.5 秒ごとに何体が鳴っているか）。
        # **「一部重なる」が指定なので数で出す** — 全部 1 なら重なっていないし、
        # 常に 4 以上なら 1 つの塊に潰れている。
        marks = [str(sum(1 for at, dur in spans
                         if ((k * 0.5 - at) % total) < dur))
                 for k in range(int(total / 0.5))]
        print(f"    0.5 秒ごとの声の数: {' '.join(marks)}")
        # ⚠ **体数を増やすときはここを見る。** 増やしたぶん「1 つの塊」に近づくので、
        #    包絡の山（＝ 別々の笑いとして聞き分けられる数）が体数について増えているかを測る。
        #    山が体数より大きく少なければ、重なりすぎて混ざっている。
        print(f"    聞き分けられそうな山: {envelope_peaks(out)} 個 / {len(spans)} 体")


def envelope_peaks(y, sr: int = None, win: float = 0.05, drop_db: float = 4.0) -> int:
    """包絡の山を数える（**別々の音として立っている数**の目安）。

    `win` 秒ごとの RMS を取り、**前後より `drop_db` 以上高い**所を 1 山とする。
    厳密な聴覚モデルではない — 体数を増やしたときに**塊へ近づいていないか**を見るためだけの物差し。
    """
    sr = sr or sk.SR
    n = int(win * sr)
    # ⚠ 3D で鳴らす音はモノで焼くので（`emit`）、ここへ 1 次元の配列が来る。
    y = sk.to_stereo(np.asarray(y))
    m = np.array([np.sqrt(np.mean(np.mean(y[i:i + n], axis=1) ** 2))
                  for i in range(0, len(y) - n, n)])
    db = 20 * np.log10(np.maximum(m, 1e-9))
    peaks = 0
    for i in range(1, len(db) - 1):
        if db[i] >= db[i - 1] and db[i] > db[i + 1]:
            lo = min(db[max(0, i - 6):i].min(initial=db[i]), db[i + 1:i + 7].min(initial=db[i]))
            if db[i] - lo >= drop_db:
                peaks += 1
    return peaks


def resample(c: np.ndarray, ratio: float) -> np.ndarray:
    """音程を変える（速さごと変える ＝ テープと同じ）。`ratio` > 1 で高く短くなる。"""
    n = max(8, int(len(c) / ratio))
    x = np.linspace(0, len(c) - 1, n)
    return np.stack([np.interp(x, np.arange(len(c)), c[:, ch]) for ch in (0, 1)], axis=1)


def time_squeeze(y: np.ndarray, s: float, sr: int,
                 frame: float = 0.030, seek: float = 0.006) -> np.ndarray:
    """**高さを変えずに尺だけ** <paramref name="s"/> 倍にする（s < 1 で短くなる）。

    波形の似ている所を探して重ねる（WSOLA）。単音の声向き — **周期の合う位置で繋ぐ**ので、
    位相をいじる方式（フェーズボコーダ）のような滲みが出ない。

    ⚠ 探す幅（`seek`）は**基音の 1 周期より広く**取る。狭いと繋ぎ目で波が食い違って
      「じりじり」が乗る（笑い素材の基音 502Hz ＝ 周期 2.0ms なので 6ms）。
    """
    n = int(frame * sr) // 2 * 2
    hs = n // 2
    ha = max(1, int(round(hs / s)))
    d = int(seek * sr)
    win = np.hanning(n + 1)[:n][:, None]
    m = len(y)
    # ⚠ **尻に窓 1 枚ぶんの無音を足してから回す。** 足さないと最後の窓が置けず、
    #   **素材の減衰の終わり（笑いの余韻）が丸ごと落ちる**。実測: 落ちると輪の継ぎ目の
    #   手前が完全な無音になり、`sound-lint.py` の密度差が +10dB 悪化した。
    y = np.pad(y, ((0, n + d), (0, 0)))
    out = np.zeros((int(m * s) + 2 * n, y.shape[1]))
    wsum = np.zeros((len(out), 1))
    ref = y[:n]
    pos = 0
    o = 0
    while pos + n + d < len(y) and o + n < len(out):
        lo = max(0, pos - d)
        hi = min(len(y) - n, pos + d)
        if hi <= lo or len(ref) < n:
            best = max(0, min(pos, len(y) - n))
        else:
            seg = y[lo:hi + n].mean(axis=1)
            cc = np.correlate(seg, ref.mean(axis=1), mode="valid")
            sq = np.concatenate([[0.0], np.cumsum(seg ** 2)])
            nrm = np.sqrt(np.maximum(sq[n:n + len(cc)] - sq[:len(cc)], 0.0) + 1e-9)
            best = lo + int(np.argmax(cc / nrm))
        out[o:o + n] += y[best:best + n] * win
        wsum[o:o + n] += win
        ref = y[best + hs:best + hs + n]
        pos += ha
        o += hs
    k = int(m * s)
    return out[:k] / np.maximum(wsum[:k], 1e-6)


def _cep_env(mag: np.ndarray, lifter: int) -> np.ndarray:
    """倍音の櫛を均して**声色（包絡）だけ**を取り出す（ケプストラム）。"""
    c = np.fft.irfft(np.log(mag + 1e-9), axis=0)
    c[lifter:-lifter] = 0.0
    return np.exp(np.fft.rfft(c, axis=0).real)


def keep_formant(z: np.ndarray, y: np.ndarray, n: int = 2048, hop: int = 512,
                 lifter: int = 42, cap_db: float = 14.0,
                 floor_db: float = -60.0, top_hz: float = 5000.0,
                 sr: int = None, amount: float = 1.0) -> np.ndarray:
    """<paramref name="z"/>（高さを下げた音）の**声色を** <paramref name="y"/>（元）**へ戻す**。

    高さを下げると声色も一緒に下がって「体格の大きい別人」になる。同じ時刻の元の包絡で
    割り戻せば、**声帯だけが低い同じ人**に戻る。⚠ やっているのは時間で変わるフィルタ 1 枚で、
    倍音そのものには触らない。

    ⚠ 持ち上げ幅に蓋（`cap_db`）を掛ける。1 オクターブ下げると**上の 1 オクターブが空になる**ので、
      蓋が無いとそこの雑音だけを 40dB 持ち上げて「しゃりしゃり」が出る。

    ⚠⚠ **無音の所は素通しにする**（`floor_db`）。音が鳴っていない枠にも包絡の比は掛かるので、
      **床の雑音だけが最大 14dB 動く**。耳には何も起きないが、**輪の継ぎ目の密度差が
      10dB 悪化して `sound-lint.py` が落ちる**（笑いは 3.4 秒に 1 回で、継ぎ目の手前は無音）。

    ⚠⚠ **上の方は戻さない**（`top_hz`）。高さを 0.45 倍に下げると **5.4kHz より上が空になる**ので、
      そこを「元と同じ濃さへ」持ち上げると**補間の雑音だけを 14dB 上げる**ことになる。
      実測: 蓋を全帯域に掛けると波高が **18.5 → 25.1dB** へ膨らみ（＝ 棘が立つ）、
      -3dBTP の天井に当たってラウドネスが 1.4dB 削られた。上限を 5kHz にすると 19.9dB で収まる。
      声の共鳴は 5kHz より下にあり、素材自体 4.7kHz より上をほとんど持っていない。
    """
    win = np.hanning(n + 1)[:n][:, None]
    m = min(len(z), len(y))
    # ⚠⚠ **頭と尻に窓 1 枚ぶんの無音を足す。** 足さないと最初の数標本を覆う窓が 1 枚しかなく、
    #    窓の重みがほぼ 0 の所で**その重みで割ることになって 100 倍に化ける**
    #    （実測: 素材の頭 5ms の尖頭が 0.00085 → 0.092 ＝ 聞こえる打撃音が付いた）。
    z = np.pad(z[:m], ((n, n), (0, 0)))
    y = np.pad(y[:m], ((n, n), (0, 0)))
    out = np.zeros((m + 3 * n, z.shape[1]))
    wsum = np.zeros((len(out), 1))
    cap = 10 ** (cap_db / 20.0)
    floor = np.abs(y).max() * 10 ** (floor_db / 20.0)
    # 上の方へ向かって 1.0（素通し）へ寄せる帯（1 オクターブかけて渡す）。
    f = np.fft.rfftfreq(n, 1.0 / (sr or sk.SR))
    lead = np.clip(np.log2(np.maximum(f, 1.0) / top_hz), 0.0, 1.0)[:, None]
    for i in range(0, len(z) - n + 1, hop):
        zf, yf = z[i:i + n], y[i:i + n]
        Z = np.fft.rfft(zf * win, axis=0)
        if np.sqrt((yf ** 2).mean()) > floor:
            g = np.clip(_cep_env(np.abs(np.fft.rfft(yf * win, axis=0)), lifter)
                        / (_cep_env(np.abs(Z), lifter) + 1e-9), 1.0 / cap, cap)
            Z = Z * (g ** (amount * (1.0 - lead)))
        out[i:i + n] += np.fft.irfft(Z, n=n, axis=0) * win
        wsum[i:i + n] += win ** 2
    # 足した無音を捨てて元の位置へ戻す（重みは 4 枚ぶん乗っているので割れる）。
    return (out[n:n + m] / np.maximum(wsum[n:n + m], 1e-6))


def keep_shape(z: np.ndarray, y: np.ndarray, sr: int,
               win: float = 0.020, cap_db: float = 12.0) -> np.ndarray:
    """<paramref name="z"/> の**大きさの移り変わり**を <paramref name="y"/>（元）へ合わせる。

    ⚠⚠ **笑いの余韻が痩せるのを防ぐ。** 重ねて繋ぐ方式（WSOLA）は、息のような
    でたらめな成分を重ねると打ち消し合って **3dB ほど失う**。実測: 本体は -6.5dB
    下がったのに、余韻（0.8〜2.2 秒）は **-9dB** 下がっていた ＝ 余韻だけが 2.5dB 痩せた。
    0110 の「尻を切ってはいけない（余韻が消えて乾いた音になる）」と同じものを、
    切らずに痩せさせていたことになる。

    ⚠ これは音量の処理（§4.5 で掛けてよい側）。圧縮とは逆向き — **元の形へ戻す**だけ。
    """
    k = int(win * sr)
    n = min(len(z), len(y))
    idx = np.arange(0, n - k, k // 2)
    if len(idx) < 2:
        return z
    ry = np.array([np.sqrt(np.mean(y[i:i + k] ** 2)) for i in idx]) + 1e-12
    rz = np.array([np.sqrt(np.mean(z[i:i + k] ** 2)) for i in idx]) + 1e-12
    cap = 10 ** (cap_db / 20.0)
    g = np.clip(ry / rz, 1.0 / cap, cap)
    return z[:n] * np.interp(np.arange(n), idx + k // 2, g)[:, None]


def pitch_down(y: np.ndarray, ratio: float, sr: int,
               formant: float = 1.0) -> np.ndarray:
    """**尺と声色を変えずに高さだけ** <paramref name="ratio"/> 倍にする（<see cref="LAUGH_PITCH"/>）。

    尺を `ratio` 倍へ縮めてから `ratio` 倍の速さで読む ＝ **尺は元どおり・高さだけ下がる**。
    そのあと声色を元へ戻す（<see cref="keep_formant"/>）。

    <paramref name="formant"/> は**声色をどれだけ戻すか** 0..1。
    1 ＝ 同じ女の子が低い声で笑う / 0 ＝ 体格の大きい別人（`tools/laugh-lab/` で聴き比べられる）。
    """
    if abs(ratio - 1.0) < 1e-6:
        return y
    z = resample(time_squeeze(y, ratio, sr), ratio)
    if len(z) < len(y):
        z = np.pad(z, ((0, len(y) - len(z)), (0, 0)))
    z = z[:len(y)]
    return keep_shape(keep_formant(z, y, sr=sr, amount=float(formant)) if formant else z, y, sr)


def laugh_source(y: np.ndarray, sr: int) -> np.ndarray:
    """笑い素材を輪へ並べる前の姿（`CHORUS` と `SWELL` で**同じもの**を使う）。

    ⚠ **高さと速さを変えるのはここ 1 か所**（40 回・9 回と並べたあとで掛けると別々にずれる）。
    """
    src = sk.env_fade(sk.to_stereo(trim(y)), 0.004, 0.02)
    if abs(LAUGH_SPEED - 1.0) > 1e-3:
        # ⚠ **速さが先、高さが後**（調整台と同じ順。逆にすると倍率の掛かり方が変わる）。
        src = time_squeeze(src, 1.0 / LAUGH_SPEED, sr)
    return pitch_down(src, LAUGH_PITCH, sr)


def pan_lr(p: float) -> np.ndarray:
    """左右へ等パワーで振る係数（片側へ寄せるだけなのでモノにしても消えない）。"""
    return np.array([np.cos((p + 1) * np.pi / 4), np.sin((p + 1) * np.pi / 4)]) * np.sqrt(2)


def short_lufs(y: np.ndarray, a: float, b: float, sr: int = None) -> float:
    """`a`〜`b` 秒だけのラウドネス（**尺に依らない高さ**を見るため）。"""
    sr = sr or sk.SR
    s = y[int(a * sr):int(b * sr)]
    return sk.lufs(s) if len(s) > 100 else -99.0


def swarm_fall_db(u: float) -> float:
    return float(np.interp(u, [k[0] for k in SWARM_FALL_KNOTS],
                           [k[1] for k in SWARM_FALL_KNOTS]))


def swarm_grain_len(u: float) -> float:
    return SWARM_GRAIN_HEAD * (SWARM_GRAIN_TAIL / SWARM_GRAIN_HEAD) ** (u ** SWARM_GRAIN_POW)


def swarm_step(u: float) -> float:
    """刻み。**画の縁（PullAt / CloseAt）で折れる。**"""
    if u <= SWARM_KNEE_U:
        return SWARM_STEP_HEAD + (SWARM_STEP_KNEE - SWARM_STEP_HEAD) * (u / SWARM_KNEE_U)
    if u <= SWARM_SETTLE_U:
        return SWARM_STEP_KNEE * (SWARM_STEP_TAIL / SWARM_STEP_KNEE) ** (
            (u - SWARM_KNEE_U) / (SWARM_SETTLE_U - SWARM_KNEE_U))
    return SWARM_STEP_TAIL


def swarm_shard(st: np.ndarray, sr: int, at: float, length: float,
                fade_out: float = 0.012) -> np.ndarray:
    """素材の途中から 1 粒を切る。**頭のフェードは 0.4ms**（一撃を鈍らせない最小）。"""
    a = int(at * sr)
    s = st[a:a + int(length * sr)]
    return sk.env_fade(s, 0.0004, min(fade_out, length * 0.35))


def swarm_build(y, sr: int, head_lufs: float):
    """1 発の録音を小刻みに並べて、**t=0 に一撃を置き、散って静まる**群れにする。

    ⚠ **等間隔・等音量にしない。** そうすると「割れた」ではなく「連射した」に聞こえる。
    ⚠ **粒の長さを時間で縮める。** 頭は長い粒が重なって轟き、尻は破片 1 つが単独で鳴る。
      密度だけで弧を作ると、頭の音量（＝ 重なりの数）を density と一緒に失う。
    """
    st = sk.to_stereo(trim(y))
    rng = np.random.default_rng(SWARM_SEED)
    n = int((SWARM_SEC + 0.40) * sr)
    out = np.zeros((n, 2))

    # ① t=0 の一撃（大きい破片が 1 つ割れる）。ここが 25ms 窓の山になる。
    for (at, idx, ratio, db, p) in SWARM_IMPACT:
        g = resample(swarm_shard(st, sr, SWARM_SHARD_AT[idx], SWARM_IMPACT_LEN, 0.030), ratio)
        i = int(at * sr)
        out[i:i + len(g)] += g * 10 ** (db / 20.0) * pan_lr(p)

    # ② 散っていく破片
    t, count, head_n = 0.012, 0, 0
    pops = list(SWARM_POP_AT)
    while t < SWARM_SEC:
        u = t / SWARM_SEC
        gl = swarm_grain_len(u)
        # 粒が短い ＝ 破片 1 つなので、素材の中の一撃から引く。長いあいだは押し込みから。
        idx = 0 if gl > SWARM_SHARD_LONG else int(rng.choice(len(SWARM_SHARD_AT),
                                                            p=SWARM_SHARD_MIX))
        ratio = (SWARM_PITCH_HEAD + (SWARM_PITCH_TAIL - SWARM_PITCH_HEAD) * u
                 + float(rng.uniform(-SWARM_PITCH_SPREAD, SWARM_PITCH_SPREAD)))
        g = resample(swarm_shard(st, sr, SWARM_SHARD_AT[idx], gl), max(0.35, ratio))
        amp = 10 ** (swarm_fall_db(u) / 20.0)
        amp *= 10 ** (float(rng.uniform(-SWARM_GAIN_JITTER_DB, SWARM_GAIN_JITTER_DB)) / 20.0)
        if pops and u >= pops[0]:
            amp *= 10 ** (SWARM_POP_DB / 20.0)
            pops.pop(0)
        p = float(rng.uniform(-1, 1)) * (SWARM_PAN_MIN
                                         + (SWARM_PAN_MAX - SWARM_PAN_MIN) * u)
        i = int(t * sr)
        seg = g * amp * pan_lr(p)
        out[i:i + len(seg)] += seg
        if t < 0.45:
            head_n += 1
        t += swarm_step(u) * (1.0 + float(rng.uniform(-SWARM_STEP_JITTER,
                                                      SWARM_STEP_JITTER)))
        count += 1

    out = sk.env_fade(out, 0.0, 0.05)
    nz = np.where(np.max(np.abs(out), axis=1) > 1e-5)[0]
    if len(nz):
        out = out[:nz[-1] + 1]

    # ③ **頭 0.5 秒の高さ**で揃える（届かなければ必要なぶんだけ尖頭を丸める）。
    drive = 0.0
    while True:
        z = sk.soft_clip(out, drive) if drive > 0 else out
        g = 10 ** ((head_lufs - short_lufs(z, 0.0, SWARM_HEAD_WIN, sr)) / 20.0)
        tp = sk.true_peak_db(z * g)
        if tp <= -3.0 or drive >= SWARM_DRIVE_MAX:
            z = z * g if tp <= -3.0 else z * g * 10 ** ((-3.0 - tp) / 20.0)
            return z, count, head_n, drive
        drive += 0.5


def switch_build(y, sr: int):
    """1 本の切替音から**毎回すこしずつ違う**変種を焼く（<see cref="SWITCH_VARIANTS"/>）。

    ⚠⚠ **1 本ずつ高さを揃えない。** ラウドネスは尺の関数なので、尾を短くしただけの変種が
    「短いぶん平均が高い」と判定されて小さく絞られる（`CUTS` の教訓と同型で向きが逆）。
    揃えるのは**頭 35ms の実効値**で、そこがこの音の身元。そのあと **1 本目で決めた
    丸めと倍率を 6 本すべてへ掛ける**。
    """
    src = sk.env_fade(sk.to_stereo(trim(y)), 0.0008, 0.008)

    def one(head_ratio, tail_at, tail_len, tail_ratio, tail_db, *_):
        head = resample(sk.env_fade(src[:int(SWITCH_HEAD_SEC * sr)], 0.0, 0.006), head_ratio)
        out = np.zeros((int(0.32 * sr), 2))
        out[:len(head)] += head
        if tail_db > -50.0:
            a = int(SWITCH_TAIL_AT * sr)
            tail = sk.env_fade(src[a:a + int(tail_len * sr)], 0.002,
                               min(SWITCH_TAIL_FADE, tail_len * 0.30))
            tail = resample(tail, tail_ratio) * 10 ** (tail_db / 20.0)
            i = int(tail_at * sr)
            out[i:i + len(tail)] += tail
        out = sk.env_fade(out, 0.0, 0.008)
        nz = np.where(np.max(np.abs(out), axis=1) > 1e-5)[0]
        return out[:nz[-1] + 1] if len(nz) else out

    def head_db(z, sec=0.035):
        s = z[:int(sec * sr)]
        return 20 * np.log10(max(float(np.sqrt(np.mean(s ** 2))), 1e-9))

    built = [one(*v) for v in SWITCH_VARIANTS]
    ref = head_db(built[0])
    built = [b * 10 ** (float(np.clip(ref - head_db(b), -3.0, 3.0)) / 20.0) for b in built]

    drive = 0.0
    while True:
        z = sk.soft_clip(built[0], drive) if drive > 0 else built[0]
        g = 10 ** ((SWITCH_LUFS - sk.lufs(z)) / 20.0)
        if sk.true_peak_db(z * g) <= -3.0 or drive >= 12.0:
            break
        drive += 0.5
    built = [(sk.soft_clip(b, drive) if drive > 0 else b) * g for b in built]
    tp = max(sk.true_peak_db(b) for b in built)
    if tp > -3.0:
        built = [b * 10 ** ((-3.0 - tp) / 20.0) for b in built]
    return built, drive


def drum_build(y, sr: int):
    """1 発の太鼓から**毎回すこしずつ違う**変種を焼く（<see cref="EYE_VARIANTS"/>）。

    ⚠ <see cref="switch_build"/> と**同じ手順**（頭を毎回そのまま置き、尾だけ変える。高さは
    頭の実効値で揃えてから 1 本目で決めた倍率を全部へ掛ける）。違うのは長さの定数だけ。
    """
    src = sk.env_fade(sk.to_stereo(trim(y)), 0.0008, 0.010)

    def one(head_ratio, tail_at, tail_len, tail_ratio, tail_db, *_):
        head = resample(sk.env_fade(src[:int(EYE_HEAD_SEC * sr)], 0.0, 0.010), head_ratio)
        out = np.zeros((int(EYE_BUF_SEC * sr), 2))
        n = min(len(head), len(out))
        out[:n] += head[:n]
        if tail_db > -50.0:
            a = int(EYE_TAIL_AT * sr)
            tail = sk.env_fade(src[a:a + int(tail_len * sr)], 0.004,
                               min(EYE_TAIL_FADE, tail_len * 0.30))
            tail = resample(tail, tail_ratio) * 10 ** (tail_db / 20.0)
            i = int(tail_at * sr)
            m = min(len(tail), len(out) - i)
            if m > 0:
                out[i:i + m] += tail[:m]
        out = sk.env_fade(out, 0.0, 0.012)
        nz = np.where(np.max(np.abs(out), axis=1) > 1e-5)[0]
        return out[:nz[-1] + 1] if len(nz) else out

    def head_db(z, sec=0.120):
        s = z[:int(sec * sr)]
        return 20 * np.log10(max(float(np.sqrt(np.mean(s ** 2))), 1e-9))

    built = [one(*v) for v in EYE_VARIANTS]
    ref = head_db(built[0])
    built = [b * 10 ** (float(np.clip(ref - head_db(b), -3.0, 3.0)) / 20.0) for b in built]

    drive = 0.0
    while True:
        z = sk.soft_clip(built[0], drive) if drive > 0 else built[0]
        g = 10 ** ((EYE_LUFS - sk.lufs(z)) / 20.0)
        if sk.true_peak_db(z * g) <= -3.0 or drive >= 12.0:
            break
        drive += 0.5
    built = [(sk.soft_clip(b, drive) if drive > 0 else b) * g for b in built]
    tp = max(sk.true_peak_db(b) for b in built)
    if tp > -3.0:
        built = [b * 10 ** ((-3.0 - tp) / 20.0) for b in built]
    return built, drive


def ingest_eyes(variants, src_dir: str) -> None:
    """目が 1 つ開くたびの一撃を焼く（<see cref="EYE_VARIANTS"/>・0131）。"""
    if not variants:
        return
    jp, stem = EYE_SRC
    raw = os.path.join(RAW, f"src_{stem}.wav")
    src = os.path.join(src_dir, jp)
    if os.path.exists(src):
        if not decode(src, raw):
            return
    elif not os.path.exists(raw):
        print(f"  無い: {jp}（{src_dir} にも {RAW} にも）")
        return
    else:
        print(f"  元 mp3 が無いので復号済みを使う: {stem}")

    y, sr = sk.read_wav(raw)
    built, drive = drum_build(y, sr)
    print(f"  {stem}_1..{len(built)}  丸め {drive:.1f}dB を {len(built)} 本へ（頭 120ms で揃えてある）")
    for i, (b, v) in enumerate(zip(built, variants), start=1):
        b = emit(f"{stem}_{i}", b)
        d = sk.describe(b)
        print(f"    {stem}_{i:<12d} {d['sec']:5.3f}s  {d['lufs']:6.1f} LUFS  "
              f"tp {d['true_peak_db']:5.2f}dB  鋭さ {d['sharp']:4.2f}  "
              f"内蔵SP {d['speaker_db']:5.1f}dB — {v[5]}")


def ingest_switch(variants, src_dir: str) -> None:
    """カメラ切替の変種を焼く（<see cref="SWITCH_VARIANTS"/>）。

    ⚠ **`MIXES` より先に呼ぶ。** 警告つきはこの 6 本を土台にする。
    """
    if not variants:
        return
    jp, stem = SWITCH_SRC
    raw = os.path.join(RAW, f"src_{stem}_1.wav")
    src = os.path.join(src_dir, jp)
    if os.path.exists(src):
        if not decode(src, raw):
            return
    elif not os.path.exists(raw):
        print(f"  無い: {jp}（{src_dir} にも {RAW} にも）")
        return
    else:
        print(f"  元 mp3 が無いので復号済みを使う: {stem}")

    y, sr = sk.read_wav(raw)
    built, drive = switch_build(y, sr)
    print(f"  {stem}_1..{len(built)}  丸め {drive:.1f}dB を 6 本へ（頭 35ms で揃えてある）")
