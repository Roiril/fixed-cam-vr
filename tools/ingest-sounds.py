#    ・尖頭で揃える（§3 の「一度きりの山」＝ -3dBTP）と **-17.3 LUFS** ＝ 本編でいちばん大きい音に
#      なる。声は 0.012 秒で立ち上がる一撃ではないので驚かしにはなりにくいが、
#      §1（劇伴を足さない ＝ 作者が怖いと叫ばない）に近い所まで寄る
#    ・⚠ **ここが最初の赤入れ点**。「小さい」と言われたら -17.3 まで、
#      「驚く」と言われたら切替音と同じ -23.0 まで。動かすのはこの 1 数字だけ
