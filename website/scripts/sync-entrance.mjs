// Copy the authored Quest timing and audio without re-editing the recordings.
import { readFile, writeFile, copyFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const read = path => readFile(resolve(root, path), 'utf8');
const hlsl = await read('Assets/Art/Shaders/Intro/IntroFractureTime.hlsl');
const intro = await read('Assets/Scripts/Streaming/IntroLogic.cs');
const cues = await read('Assets/Scripts/Streaming/Sound/SoundCueLogic.cs');
const player = await read('Assets/Scripts/Streaming/Sound/SfxPlayer.cs');
const show = JSON.parse(await read('tools/web-compositor/show.json'));
function number(source, pattern) {
  const value = source.match(pattern)?.[1];
  if (!value) throw new Error(`Missing Quest value: ${pattern}`);
  return Number(value);
}
const timing = Object.fromEntries([
  'CrackEnd', 'BreakSpan', 'PullBegin', 'PullArrest', 'PullStart', 'BurstTau',
  'DriftRate', 'ArriveFirst', 'ArriveSpan', 'PullPowLight', 'PullPowHeavy', 'CloserArrive'
].map(key => [key, number(hlsl, new RegExp(`float ${key} = ([0-9.]+);`))]));
const durations = [];
function findIntro(value) {
  if (!value || typeof value !== 'object') return;
  if (value.intro?.frameSec) durations.push(value.intro.frameSec);
  Object.values(value).forEach(findIntro);
}
findIntro(show);
timing.duration = (durations[0] ?? number(intro, /frameSec = ([0-9.]+)f/)) * 1000;
timing.shatterAt = number(cues, /ShatterFireAt = ([0-9.]+)f/);
timing.audioLead = number(player, /ScheduleLeadSec = ([0-9.]+)f/);
await writeFile(resolve(root, 'website/entrance-timing.js'),
  `// Generated by scripts/sync-entrance.mjs from the Quest implementation.\nwindow.MAWARIMI_ENTRANCE_TIMING = Object.freeze(${JSON.stringify(timing, null, 2)});\n`);
for (const name of ['sfx_shatter']) {
  await copyFile(resolve(root, `Assets/Resources/Sound/${name}.wav`), resolve(root, `website/assets/${name}.wav`));
}
console.log(JSON.stringify(timing, null, 2));
